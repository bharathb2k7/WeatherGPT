export function getLanguageInfo(langCode: string): LanguageInfo {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.code === langCode) || {
      code: langCode,
      name: langCode.toUpperCase(),
      nativeName: langCode.toUpperCase(),
      category: "Global",
    }
  );
}
